export function generateSentenceTokens(count, difficulty = "easy") {
  const sentences = difficulty === "hard" ? HARD_SENTENCES : difficulty === "medium" ? MEDIUM_SENTENCES : EASY_SENTENCES;
  const tokens = [];
  while (tokens.length < count) {
    const sentence = sentences[Math.floor(Math.random() * sentences.length)];
    tokens.push(...sentence.split(" ").filter((t) => t.length > 0));
  }
  return tokens.slice(0, count);
}

export function generateFromList(count, list) {
  const out = [];
  for (let i = 0; i < count; i++) {
    out.push(list[Math.floor(Math.random() * list.length)]);
  }
  return out;
}

export function generateWords(count, difficulty = "easy") {
  const pool = difficulty === "hard" ? HARD_WORDS : difficulty === "medium" ? MEDIUM_WORDS : EASY_WORDS;
  return generateFromList(count, pool);
}
